ALLOWED_CATEGORIES = [
    "Еда",
    "Транспорт",
    "Электроника",
    "Одежда",
    "Здоровье",
    "Развлечения",
    "Коммунальные услуги",
    "Прочее",
]


def build_receipt_prompt(raw_text: str, categories: list[str] | None = None) -> str:
    category_list = categories or ALLOWED_CATEGORIES
    joined = ", ".join(category_list)
    return f"""Ты извлекаешь поля из OCR-текста кассового чека.
Верни ТОЛЬКО один JSON-объект без markdown и без пояснений.

Схема:
{{
  "merchant_name": "строка или null",
  "amount": число или null,
  "currency": "RUB|UAH|USD|EUR или null",
  "date": "YYYY-MM-DD или null",
  "category": "одна из [{joined}]",
  "items": [{{"name": "строка", "price": число, "quantity": число}}],
  "confidence": "high|medium|low"
}}

Правила:
- Игнорируй ИНН/ЄДРПОУ, номер терминала, код авторизации, ФН/ФД/ФП, номер карты при поиске суммы и даты.
- Сумма чека — это ИТОГ/ВСЕГО/СУМА/РАЗОМ покупки, НЕ "НАЛИЧНЫМИ"/"ГОТІВКИ"/"ПОЛУЧЕНО" и НЕ "СДАЧА"/"РЕШТА".
- "ГОТІВКА" (без И) часто = способ оплаты на сумму чека; "ГОТІВКИ" = купюры, которые дали в кассу.
- Если есть наличные и сдача: сумма = наличные − сдача.
- Если OCR дал несколько разных СУМА/ИТОГ — бери значение, которое повторяется чаще (consensus).
- OCR часто путает М/Н (МАГНИТ→НАГНИТ); исправляй известные сети по смыслу.
- Сумма обычно рядом с Итого/Сумма/К оплате (RU), Сума/Всього/Разом/До сплати (UA), Total/Amount (EN).
- Числа могут иметь пробел как разделитель тысяч, например "4 199.00".
- Дата покупки обычно рядом со временем операции ЧЧ:ММ; год может быть двузначным (15 → 2015).
- Если поле неуверенно — верни null, не выдумывай.
- category бери только из списка выше; если неясно — "Прочее".
- Кафе/ресторан/кофе/стейк/салат/капучино → "Развлечения" (не Транспорт).
- АЗС/бензин → "Транспорт". Аптека/таблетки → "Здоровье".
- items: позиции товаров если видны, иначе [].

OCR текст чека:
<<<
{raw_text}
>>>
"""
